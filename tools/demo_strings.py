"""Copies the app's texts, licences and fonts into the browser demo (demo/), so the demo never drifts
from the app: run it after changing res/values*/strings.xml, res/raw/licenses.txt or res/font.

    py -I tools/demo_strings.py
"""
import json
import re
import shutil
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app" / "src" / "main" / "res"
DEMO = ROOT / "demo"


def unescape(text: str) -> str:
    # Android resource escapes: \' \" \n \t \@ \? and \uXXXX; surrounding quotes keep spaces.
    text = text.strip()
    if len(text) >= 2 and text[0] == '"' and text[-1] == '"':
        text = text[1:-1]
    text = re.sub(r"\\u([0-9a-fA-F]{4})", lambda m: chr(int(m.group(1), 16)), text)
    return (text.replace("\\n", "\n").replace("\\t", "\t").replace("\\'", "'")
            .replace('\\"', '"').replace("\\@", "@").replace("\\?", "?"))


def inner(el: ET.Element) -> str:
    # Keeps the text of nested tags (e.g. <xliff:g>) - the demo has no styled spans.
    return "".join(el.itertext())


def read(path: Path) -> dict:
    out = {}
    for el in ET.parse(path).getroot():
        name = el.get("name")
        if el.tag == "string":
            out[name] = unescape(inner(el))
        elif el.tag == "plurals":
            out[name] = {item.get("quantity"): unescape(inner(item)) for item in el}
    return out


def main() -> int:
    pl = read(RES / "values" / "strings.xml")
    en = dict(pl)  # untranslatable strings (names, formats) live only in values/
    en.update(read(RES / "values-en" / "strings.xml"))
    licenses = (RES / "raw" / "licenses.txt").read_text(encoding="utf-8")
    js = (
        "// Generated by tools/demo_strings.py from the app's resources - do not edit by hand.\n"
        "window.TAPEDO_STRINGS = " + json.dumps({"pl": pl, "en": en}, ensure_ascii=False, indent=0) + ";\n"
        "window.TAPEDO_LICENSES = " + json.dumps(licenses, ensure_ascii=False) + ";\n"
    )
    (DEMO / "strings.js").write_text(js, encoding="utf-8")
    fonts = DEMO / "fonts"
    fonts.mkdir(exist_ok=True)
    for font in (RES / "font").glob("*.ttf"):
        shutil.copyfile(font, fonts / font.name)
    print(f"strings: {len(pl)} pl, {len(en)} en; fonts copied")
    return 0


if __name__ == "__main__":
    sys.exit(main())
